class TestReportSchema:
    """Tests for JSON report structure."""

    def test_packets_array_exists(self):
        """Report must have a packets array."""
        report = load_report()
        assert "packets" in report
        assert isinstance(report["packets"], list)
        assert len(report["packets"]) == 15

    def test_summary_exists(self):
        """Report must have a summary object."""
        report = load_report()
        assert "summary" in report

    def test_packet_fields(self):
        """Each packet entry must have required fields."""
        report = load_report()
        required = {
            "packet_id", "stage_id", "expected_checksum",
            "actual_checksum", "drift_score", "reconciled",
            "payload_size", "entry_count",
        }
        for pkt in report["packets"]:
            missing = required - set(pkt.keys())
            assert not missing, f"{pkt.get('packet_id')}: missing {missing}"

    def test_checksum_hex_format(self):
        """Checksums must be formatted as 0xXXXXXXXX."""
        report = load_report()
        for pkt in report["packets"]:
            assert pkt["expected_checksum"].startswith("0x")
            assert len(pkt["expected_checksum"]) == 10
            assert pkt["actual_checksum"].startswith("0x")
            assert len(pkt["actual_checksum"]) == 10

    def test_sort_order(self):
        """Packets must be sorted by stage_id then packet_id."""
        report = load_report()
        packets = report["packets"]
        for i in range(len(packets) - 1):
            a, b = packets[i], packets[i + 1]
            if a["stage_id"] == b["stage_id"]:
                assert a["packet_id"] <= b["packet_id"], (
                    f"Sort violated: {a['packet_id']} > {b['packet_id']}"
                )
            else:
                assert a["stage_id"] < b["stage_id"]


class TestAntiCheat:
    """Anti-cheating tests with independently computed values."""

    def test_independent_checksum_pkt_001(self):
        """Independently verify checksum for pkt_001 (simple, in-order)."""
        report = load_report()
        with open(JOURNAL_PATH) as f:
            journal = json.load(f)

        # Get pkt_001 entries sorted by sequence_num
        pkt_entries = sorted(
            [e for e in journal["entries"] if e["packet_id"] == "pkt_001"],
            key=lambda e: e["sequence_num"],
        )

        # Accumulate state
        seed = 0x5678
        state = b""
        accumulated = seed
        for entry in pkt_entries:
            payload = bytes.fromhex(entry["payload"])
            entry_hash = compute_hash(payload, entry["stage_id"])
            accumulated = accumulated ^ entry_hash
            state += payload

        # Stage checksum
        stage_cs = compute_stage_checksum(state, 1, seed)
        expected = stage_cs ^ accumulated

        pkt = next(p for p in report["packets"] if p["packet_id"] == "pkt_001")
        assert pkt["expected_checksum"] == f"0x{expected:08X}", (
            f"pkt_001: expected 0x{expected:08X}, got {pkt['expected_checksum']}"
        )

    def test_independent_checksum_pkt_004(self):
        """Independently verify pkt_004 (12 entries, needs full window)."""
        report = load_report()
        with open(JOURNAL_PATH) as f:
            journal = json.load(f)

        pkt_entries = sorted(
            [e for e in journal["entries"] if e["packet_id"] == "pkt_004"],
            key=lambda e: e["sequence_num"],
        )
        assert len(pkt_entries) == 12

        seed = 0x5678
        state = b""
        accumulated = seed
        for entry in pkt_entries:
            payload = bytes.fromhex(entry["payload"])
            entry_hash = compute_hash(payload, entry["stage_id"])
            accumulated = accumulated ^ entry_hash
            state += payload

        stage_cs = compute_stage_checksum(state, 2, seed)
        expected = stage_cs ^ accumulated

        pkt = next(p for p in report["packets"] if p["packet_id"] == "pkt_004")
        assert pkt["expected_checksum"] == f"0x{expected:08X}"

