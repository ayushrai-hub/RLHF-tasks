def compute_sha256(path):
    """Compute SHA-256 of a file."""
    h = hashlib.sha256()
    with open(path, "rb") as f:
        h.update(f.read())
    return h.hexdigest()


JOURNAL_SHA256 = None
CONFIG_SHA256 = None


def _init_hashes():
    global JOURNAL_SHA256, CONFIG_SHA256
    if JOURNAL_SHA256 is None:
        JOURNAL_SHA256 = compute_sha256(JOURNAL_PATH)
        CONFIG_SHA256 = compute_sha256(CONFIG_PATH)


_init_hashes()


def compute_hash(data, stage_id):
    """Independent hash computation matching the relay tool."""
    h = (stage_id * 0x9E3779B9) & 0xFFFFFFFF
    for b in data:
        h = ((h * 31) + b) & 0xFFFFFFFF
    return h


def compute_stage_checksum(data, stage_id, seed):
    """Independent stage checksum computation."""
    base = compute_hash(data, stage_id)
    return base ^ seed


