"""Tests for accaudit-wren: validates /app/audit_report.json produced by /app/audit.wren.

The bundled-fixture tests grade the report for /app/transactions.tsv. The toolchain
tests confirm the report is produced by running the required Wren program. The final
perturbation test re-runs /app/audit.wren on held-out generated schedules and
deep-compares to an independent reference, so a report hardcoded to the bundled
fixture (or a checker that skips the interest computation) cannot pass.
"""

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(__file__))
import reference  # noqa: E402
import gen  # noqa: E402

REPORT = Path("/app/audit_report.json")
WREN_SCRIPT = Path("/app/audit.wren")
SCHEDULE = Path("/app/transactions.tsv")


def load_report():
    """Load and parse /app/audit_report.json."""
    assert REPORT.exists(), f"{REPORT} not found — did wren_cli /app/audit.wren run?"
    with open(REPORT) as f:
        data = json.load(f)
    assert isinstance(data, list), "audit_report.json must be a JSON array"
    return data


def errors_with(report, *, error_code=None, txn_id=None, account_id=None):
    """Return all error records matching the given filters."""
    result = report
    if error_code is not None:
        result = [e for e in result if e.get("error_code") == error_code]
    if txn_id is not None:
        result = [e for e in result if e.get("txn_id") == txn_id]
    if account_id is not None:
        result = [e for e in result if e.get("account_id") == account_id]
    return result


def run_wren_fresh():
    """Run `wren_cli /app/audit.wren` and return the report it produces.

    Accepts both a script that prints the JSON array to stdout and one that writes
    /app/audit_report.json directly.
    """
    exe = shutil.which("wren_cli")
    assert exe is not None, "wren_cli must be available on PATH in the image"
    proc = subprocess.run([exe, str(WREN_SCRIPT)], capture_output=True, text=True, cwd="/app")
    assert proc.returncode == 0, f"`wren_cli /app/audit.wren` exited {proc.returncode}: {proc.stderr}"
    out = proc.stdout.strip()
    if out:
        try:
            data = json.loads(out)
            if isinstance(data, list):
                return data
        except json.JSONDecodeError:
            pass
    return load_report()


# ── toolchain enforcement (report must come from running the Wren program) ────

def test_audit_wren_script_exists():
    """Verify the agent created a non-empty Wren script at /app/audit.wren."""
    assert WREN_SCRIPT.exists(), "/app/audit.wren not found — the audit must be written in Wren"
    assert WREN_SCRIPT.stat().st_size > 0, "/app/audit.wren is empty"


def test_report_is_produced_by_wren_cli():
    """Verify /app/audit_report.json equals the output of `wren_cli /app/audit.wren`."""
    committed = load_report()
    produced = run_wren_fresh()
    assert produced == committed, (
        "running `wren_cli /app/audit.wren` did not reproduce /app/audit_report.json — "
        "the report must be generated by the Wren script")


