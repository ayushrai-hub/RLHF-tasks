# ── held-out perturbation / anti-hardcoding (runs last) ───────────────────────

def test_zzz_perturbation_on_generated_holdouts():
    """Re-run /app/audit.wren on generated held-out schedules; deep-compare to reference.

    A report hardcoded to the bundled fixture, or a checker that skips the interest
    accrual, diverges on these inputs. Restores the bundled schedule/report afterward.
    """
    assert WREN_SCRIPT.exists(), "/app/audit.wren not found"
    exe = shutil.which("wren_cli")
    assert exe is not None, "wren_cli must be on PATH"
    backup_schedule = SCHEDULE.read_text()
    backup_report = REPORT.read_text() if REPORT.exists() else None
    seeds = [1, 7, 13, 42, 99, 123, 777, 2024, 31337, 65535]
    seen_norm = []
    try:
        for seed in seeds:
            text = gen.generate(seed)
            SCHEDULE.write_text(text)
            if REPORT.exists():
                REPORT.unlink()
            proc = subprocess.run([exe, str(WREN_SCRIPT)], capture_output=True, text=True, cwd="/app")
            produced = None
            out = proc.stdout.strip()
            if out:
                try:
                    produced = json.loads(out)
                except json.JSONDecodeError:
                    produced = None
            if produced is None:
                assert REPORT.exists(), f"held-out seed {seed}: /app/audit.wren produced no report"
                with open(REPORT) as f:
                    produced = json.load(f)
            expected = reference.audit(text)
            assert reference.normalize(produced) == reference.normalize(expected), (
                f"held-out seed {seed}: report does not match reference\n"
                f"agent={json.dumps(reference.normalize(produced))}\n"
                f"ref={json.dumps(reference.normalize(expected))}")
            seen_norm.append(json.dumps(reference.normalize(produced), sort_keys=True))
        assert len(set(seen_norm)) > 1, "report identical across different inputs — appears hardcoded"
    finally:
        SCHEDULE.write_text(backup_schedule)
        if backup_report is not None:
            REPORT.write_text(backup_report)
